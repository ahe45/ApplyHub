const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const puppeteer = require('puppeteer-core');
const config = require('../shared/app-config');

async function verifySettingsLanguage({ services, query, base, call }) {
  await services.authService.createAccount({ id:'settings-super',name:'슈퍼관리자',role:config.superAdminRole });
  await query('UPDATE accounts SET password_temporary = 0');
  const basic = await services.systemService.getSystemSettings();
  const login = await call('/api/auth/login',{id:'settings-super',password:basic.initialPassword});
  const admin = await call('/api/auth/login',{id:'admin',password:basic.initialPassword});
  assert.equal(login.status,200);
  assert.equal((await call('/api/system-settings',null,admin.cookie,'GET')).status,403);
  assert.equal((await call('/api/system-settings',basic,admin.cookie,'PUT')).status,403);
  assert(!config.availableViews.includes('systemSettings'));
  assert(!config.sidebarMenuSections.some(section => section.views.includes('systemSettings')));
  const applicants = services.applicantService;
  await applicants.createApplicantFormField({fieldKey:'locale-choice',questionText:'시간 선택',questionTextEn:'Time',questionDescription:'시간 안내',questionDescriptionEn:'Time help',inputType:'select',options:['오전','오후'],optionsEn:{오전:'Morning',오후:'Afternoon'}});
  const field = (await applicants.getApplicantFormFields()).find(row => row.fieldKey === 'locale-choice');
  await applicants.createApplicantRecruitmentUnit({trackName:'수시',admissionCode:'1',admissionName:'일반',admissionNameEn:'General',seriesCode:'2',seriesName:'인문',unitCode:'3',unitName:'문학',unitNameEn:'Literature'});
  await services.membershipService.saveSettings({terms:[{id:'language-term',title:'한국어 약관',text:'한국어 내용',titleEn:'Terms',textEn:'English terms',enabled:true,required:true}]});
  const artifacts=path.resolve('.tmp-settings-language'); fs.mkdirSync(artifacts,{recursive:true});
  const browser=await puppeteer.launch({headless:true,executablePath:process.env.EDGE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const errors=[];
  const attach=async(context,cookie)=>{
    if(cookie){const i=cookie.indexOf('=');await context.setCookie({name:cookie.slice(0,i),value:cookie.slice(i+1),url:base});}
    const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));await page.setViewport({width:1440,height:1000});return page;
  };
  const fill=async(page,selector,value)=>{await page.$eval(selector,(node,value)=>{node.value=value;node.dispatchEvent(new Event('input',{bubbles:true}));},value);};
  const select=async(page,key,language)=>{await page.click(`[editor-key="${key}"] .language-menu-trigger`);await page.click(`[editor-key="${key}"] [data-language="${language}"]`);};
  try {
    const page=await attach(await browser.createBrowserContext(),login.cookie);
    page.on('dialog',dialog=>dialog.accept());
    await page.goto(base+'/system-settings',{waitUntil:'networkidle0'});
    assert.equal(new URL(page.url()).pathname,'/super-admin');
    assert.equal(await page.$('[data-view=systemSettings]'),null);
    for(const id of ['systemSettingsInitialPassword','systemSettingsAutoLogoutMinutes','systemSettingsAdmissionHomepageUrl']) assert(await page.$('#'+id));
    await fill(page,'#systemSettingsInitialPassword','NewDefault_2222');
    await fill(page,'#systemSettingsAutoLogoutMinutes','22');
    await fill(page,'#systemSettingsAdmissionHomepageUrl','https://example.test/admissions');
    await fill(page,'#superAdminSchoolName','언어 테스트대학교');
    await page.click('[data-super-admin-action=save]');
    await page.waitForFunction(()=>document.querySelector('#superAdminStatus')?.textContent.includes('저장했습니다'));
    const saved=await services.systemService.getSystemSettings();
    assert.equal(saved.initialPassword,'NewDefault_2222');assert.equal(saved.autoLogoutMinutes,22);assert.equal(saved.admissionHomepageUrl,'https://example.test/admissions');
    assert.equal((await services.systemService.getSuperAdminSettings()).schoolName,'언어 테스트대학교');
    await page.reload({waitUntil:'networkidle0'});assert.equal(await page.$eval('#systemSettingsAutoLogoutMinutes',el=>el.value),'22');
    await page.screenshot({path:path.join(artifacts,'super-admin.png'),fullPage:true});
    await fill(page,'#systemSettingsAutoLogoutMinutes','23');
    await page.click('[data-view=accountManagement]');
    await page.waitForFunction(()=>document.querySelector('#viewRoot') && !document.querySelector('#systemSettingsAutoLogoutMinutes'));
    assert.equal((await services.systemService.getSystemSettings()).autoLogoutMinutes,23,'Navigation saves basic settings alongside branding');
    await page.goto(base+'/applicant-question-template-management',{waitUntil:'networkidle0'});
    await page.click('.form-template-thumbnail-open');
    await page.click(`[data-applicant-field-select="${field.id}"]`);
    const title='[data-applicant-field-input=questionText]',english='[data-applicant-field-input=questionTextEn]';
    assert(await page.$eval(title,node=>!!node.getClientRects().length));assert(await page.$eval(english,node=>!node.getClientRects().length));
    await select(page,'question-application','en');
    assert(await page.$eval(title,node=>!node.getClientRects().length));assert(await page.$eval(english,node=>!!node.getClientRects().length));
    await fill(page,english,'Choose time');await fill(page,'[data-applicant-field-input="optionEnglish:0"]','AM session');
    await select(page,'question-application','ko');assert.equal(await page.$eval(english,node=>node.value),'Choose time');
    await fill(page,title,'시간을 선택하세요');await select(page,'question-application','en');
    await page.screenshot({path:path.join(artifacts,'question-english.png'),fullPage:true});
    const savedField=page.waitForResponse(response=>response.url().includes('/api/applicant-form-fields/') && response.request().method()==='PUT');
    await page.click('[data-applicant-field-form] button[type=submit]');assert.equal((await savedField).status(),200);
    const stored=(await applicants.getApplicantFormFields()).find(row=>row.id===field.id);
    assert.equal(stored.questionText,'시간을 선택하세요');assert.equal(stored.questionTextEn,'Choose time');assert.equal(stored.optionsEn.오전,'AM session');
    await page.goto(base+'/applicant-question-template-management?tab=terms',{waitUntil:'networkidle0'});
    await page.waitForSelector('[data-term-select]');await page.click('[data-term-select]');
    await select(page,'signup-terms','en');await fill(page,'[data-term-input=textEn]','Updated English terms');
    await select(page,'signup-terms','ko');assert.equal(await page.$eval('[data-term-input=textEn]',node=>node.value),'Updated English terms');
    await page.click('[data-term-form] button[type=submit]');
    await page.waitForFunction(()=>!document.querySelector('[data-term-input=textEn]')?.value);
    assert.equal((await services.membershipService.getSettings()).terms[0].textEn,'Updated English terms');
    await page.goto(base+'/login-notice',{waitUntil:'networkidle0'});
    await page.waitForSelector('[editor-key=notice-editor]');
    await select(page,'notice-editor','en');
    assert(await page.$eval('[data-notice-canvas=en]',node=>!node.hidden));assert(await page.$eval('[data-notice-canvas=ko]',node=>node.hidden));
    await page.$eval('#loginNoticeEditorEn',node=>{node.innerHTML='<p>English notice draft</p>';node.dispatchEvent(new Event('input',{bubbles:true}));});
    await select(page,'notice-editor','ko');await select(page,'notice-editor','en');
    assert((await page.$eval('#loginNoticeEditorEn',node=>node.textContent)).includes('English notice draft'));
    const noticeSave=page.waitForResponse(response=>response.url().endsWith('/api/login-notice') && response.request().method()==='PUT');
    await page.click('[data-notice-canvas=en] [data-notice-action=save]');assert.equal((await noticeSave).status(),200);
    await page.screenshot({path:path.join(artifacts,'notice-english.png'),fullPage:true});
    await page.goto(base+'/applicant-recruitment-management',{waitUntil:'networkidle0'});
    await page.click('tr[data-grid-row-clickable=true]');await page.waitForSelector('#applicantRecruitmentUnitModal:not(.hidden)');
    await select(page,'recruitment-names','en');
    assert(await page.$eval('#applicantRecruitmentAdmissionName',node=>!node.getClientRects().length));
    assert(await page.$eval('#applicantRecruitmentAdmissionNameEn',node=>!!node.getClientRects().length));
    await fill(page,'#applicantRecruitmentAdmissionNameEn','Updated General');await select(page,'recruitment-names','ko');
    assert.equal(await page.$eval('#applicantRecruitmentAdmissionNameEn',node=>node.value),'Updated General');

    const visitor=await attach(await browser.createBrowserContext());await visitor.goto(base+'/login',{waitUntil:'networkidle0'});
    const trigger='applyhub-language-toggle .language-menu-trigger';
    assert((await visitor.$eval(trigger,node=>node.textContent)).includes('Language'));
    assert(await visitor.$(trigger+' svg'));
    await visitor.click(trigger);assert(await visitor.$eval('applyhub-language-toggle .language-menu-options',node=>!node.hidden));
    await visitor.keyboard.press('Escape');assert(await visitor.$eval(trigger,node=>node.getAttribute('aria-expanded'))==='false');
    await visitor.focus(trigger);await visitor.keyboard.press('ArrowDown');await visitor.keyboard.press('ArrowDown');await visitor.keyboard.press('Enter');
    await visitor.waitForFunction(()=>document.documentElement.lang==='en');
    await visitor.reload({waitUntil:'networkidle0'});assert.equal(await visitor.$eval('html',node=>node.lang),'en');
    await visitor.setViewport({width:390,height:844});await visitor.click(trigger);
    assert(await visitor.$eval('applyhub-language-toggle .language-menu-options',node=>{const r=node.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth;}));
    await visitor.screenshot({path:path.join(artifacts,'language-dropdown-mobile.png'),fullPage:true});
    await visitor.evaluate(()=>document.documentElement.dataset.theme='dark');
    await visitor.screenshot({path:path.join(artifacts,'language-dropdown-dark.png'),fullPage:true});
    await visitor.mouse.click(2,2);assert(await visitor.$eval('applyhub-language-toggle .language-menu-options',node=>node.hidden));
    assert.deepEqual(errors,[]);
    console.log('PASS: removed menu, super-admin settings save and guard, role protection, language dropdown keyboard/mobile, question/option/terms/notice/name drafts and persistence');
  } finally {await browser.close();}
}
module.exports={verifySettingsLanguage};
