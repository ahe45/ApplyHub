const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const puppeteer = require('puppeteer-core');
const { PDFDocument } = require('pdf-lib');

async function verifyTemplateAdmissions({ services, query, base, call, submission, signup }) {
  const service = services.templateService;
  const applicant = services.applicantService;
  const schedule = (await applicant.getApplicantSchedules())[0];
  const unlinked = await service.createTemplate({ name: '미연결 양식', version: 'v1', contentHtml: '<div class="template-doc"><p>미연결</p></div>' });
  assert.equal((await service.getEditorContext(unlinked.id)).previewSource.kind, 'empty');
  await service.updateTemplate(unlinked.id, { contentHtml: '<p>변경</p>' });
  const form = (await applicant.getApplicantFormTemplates()).find(template => template.formScope === 'application' && template.isDefault);
  const otherForm = await applicant.saveApplicantFormTemplate({ formScope: 'application', name: '다른 전형 질문', copyFromId: form.id });
  await applicant.createApplicantFormField({ templateId: form.id, fieldKey: 'ticket-field', questionText: '연결 질문', inputType: 'text', required: false });
  await applicant.createApplicantFormField({ templateId: otherForm.id, fieldKey: 'other-ticket-field', questionText: '다른 전형 질문', inputType: 'text', required: false });
  await query(`INSERT INTO app_subm (id,applicant_name,email,password_hash,status,field_key,answer_data)
    SELECT id,applicant_name,email,password_hash,status,'ticket-field','이 전형의 실제 답변' FROM app_subm WHERE id=? LIMIT 1`, [submission.id]);
  await query("INSERT INTO app_unit (track_name,admission_code,admission_name,series_code,series_name,unit_code,unit_name) VALUES ('다른모집','99','다른전형','2','인문','4','언어')");
  const otherSchedule = await query("INSERT INTO app_schedule (track_name,admission_code,admission_name,application_template_id) VALUES ('다른모집','99','다른전형',?)", [otherForm.id]);
  const template = unlinked;
  const other = await service.createTemplate({ name: '다른전형 양식', version: 'v1', contentHtml: '<div class="template-doc"><p>다른전형 전용</p></div>' });
  await applicant.saveApplicantSchedule({ ...schedule, admitCardTemplateId: template.id });
  await applicant.saveApplicantSchedule({ trackName:'다른모집',admissionCode:'99',admissionName:'다른전형',applicationTemplateId:otherForm.id,admitCardTemplateId:other.id });
  const context = await service.getEditorContext(template.id);
  assert.equal(context.previewSource.submissionId, submission.id);
  assert(context.tags.some(tag => tag.token === '@{회원가입:address}'));
  assert(context.tags.some(tag => tag.token === '@{원서접수:ticket-field}'));
  assert(!context.tags.some(tag => tag.token === '@{원서접수:other-ticket-field}'));
  assert(!context.tags.some(tag => tag.label.includes('비밀번호')));
  assert.equal(context.previewRecord.signupAnswers.address, signup.profile.address);
  assert.equal(context.previewRecord.applicationAnswers['ticket-field'], '이 전형의 실제 답변');
  const otherContext = await service.getEditorContext(other.id);
  assert.equal(otherContext.previewSource.kind, 'empty', 'Another admission never borrows this admission\'s applicant');
  assert(otherContext.tags.some(tag => tag.token === '@{원서접수:other-ticket-field}'));
  assert(!otherContext.tags.some(tag => tag.token === '@{원서접수:ticket-field}'));
  const html = '<div class="template-doc"><p>회원: <span data-template-tag-value="@{회원가입:address}" style="font-size:16pt">주소</span></p><p>답변: @{원서접수:ticket-field}</p></div>';
  await service.updateTemplate(template.id, { contentHtml: html });
  const preview = await service.previewTemplate(template.id);
  assert(preview.renderedHtml.includes(signup.profile.address));
  assert(preview.renderedHtml.includes('이 전형의 실제 답변'));
  assert.equal((await service.getActiveTemplate({ track: schedule.trackName, admission: schedule.admissionName })).id, template.id);
  assert.equal((await service.getActiveTemplate({ track: '다른모집', admission: '다른전형' })).id, other.id);
  const realRecord = await applicant.buildApplicantAdmitCardRecordFromSubmission(await applicant.getApplicantSubmissionById(submission.id), { includePhoto: false });
  const printedHtml = await service.renderTemplateWithExaminee(html, realRecord);
  assert(printedHtml.includes(signup.profile.address) && printedHtml.includes('이 전형의 실제 답변'));
  const pdf = await services.admitCardService.buildAdmitCardPdfBufferFromRecord(realRecord);
  assert.equal((await PDFDocument.load(pdf)).getPageCount(), 1);
  const otherMeta = await query("INSERT INTO app_meta (examinee_no) VALUES ('OTHER-123')");
  for (const [key, value] of [['__applicant_selection_track', '다른모집'], ['__applicant_selection_admission', '다른전형']]) {
    await query("INSERT INTO app_subm (id,applicant_name,email,status,field_key,answer_data) VALUES (?,'다른지원자','other@test.example','submitted',?,?)", [otherMeta.insertId, key, value]);
  }
  const batchPdf = await services.admitCardService.buildBatchAdmitCardPdfBuffer([submission.examineeNo, 'OTHER-123']);
  assert.equal((await PDFDocument.load(batchPdf)).getPageCount(), 2);
  const login = await call('/api/auth/login', { id: 'admin', password: '1111' });
  const setup = await call('/api/auth/password/setup', { password: 'LinkedEditor1234', passwordConfirm: 'LinkedEditor1234' }, login.cookie);
  const cookie = setup.cookie || login.cookie;
  assert.equal((await call(`/api/templates/${template.id}/editor-context`, null, '', 'GET')).status, 401);
  const browser = await puppeteer.launch({ executablePath: process.env.EDGE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const output = path.resolve(__dirname, '../.tmp-template-admissions');
  fs.mkdirSync(output, { recursive: true });
  page.on('dialog', dialog => dialog.accept());
  try {
    await page.setViewport({ width: 1800, height: 1100 });
    const split = cookie.indexOf('=');
    await browser.setCookie({ name: cookie.slice(0, split), value: cookie.slice(split + 1), url: base });
    await page.goto(base + '/templates', { waitUntil: 'networkidle0' });
    const unbound = await service.createTemplate({ name:'자유편집 양식',version:'v1',contentHtml:'<p>편집 가능</p>' });
    await page.goto(`${base}/templates/${unbound.id}/edit`, { waitUntil:'networkidle0' });
    await page.waitForFunction(() => window.ApplyHubExamListEditor?.instance);
    assert(await page.$('#templateEditorPage'), 'Unassigned templates open by direct URL');
    await page.goto(base + '/templates', { waitUntil:'networkidle0' });
    const pageTexts = await page.evaluate(async bytes => {
      const pdfjs = await import('/node_modules/pdfjs-dist/legacy/build/pdf.mjs');
      pdfjs.GlobalWorkerOptions.workerSrc = '/node_modules/pdfjs-dist/legacy/build/pdf.worker.mjs';
      const task = pdfjs.getDocument({ data: Uint8Array.from(bytes) });
      const document = await task.promise;
      const texts = [];
      for (let index = 1; index <= document.numPages; index++) texts.push((await (await document.getPage(index)).getTextContent()).items.map(item => item.str).join(' '));
      await task.destroy();
      return texts;
    }, Array.from(batchPdf));
    assert(pageTexts[0].includes('이 전형의 실제 답변'));
    assert(pageTexts[1].includes('다른전형 전용'), 'Mixed batches choose the template for each admission');
    await page.waitForSelector(`[data-template-edit="${template.id}"]:not([disabled])`);
    await page.$eval(`[data-template-edit="${template.id}"]`, button => button.click());
    await page.waitForFunction(id => location.pathname === `/templates/${id}/edit`, {}, template.id);
    await page.waitForFunction(() => window.ApplyHubExamListEditor?.instance || document.querySelector('#templateEditorStatus')?.textContent.includes('못했습니다'));
    assert(await page.evaluate(() => !!window.ApplyHubExamListEditor.instance), await page.$eval('#templateEditorStatus', el => el.textContent));
    assert.equal(await page.$('#templateEditorModal'), null, 'Editor is a page, with no editor modal');
    assert((await page.$eval('#templateTagStrip', el => el.textContent)).includes('회원가입'));
    assert((await page.$eval('#templateTagStrip', el => el.textContent)).includes('원서접수'));
    assert((await page.$eval('#templateEditorSurface', el => el.textContent)).includes(signup.profile.address));
    assert((await page.$eval('#templateEditorSurface', el => el.textContent)).includes('이 전형의 실제 답변'), 'Bare namespaced tokens become linked editable tags');
    await page.screenshot({ path: path.join(output, 'editor-page.png'), fullPage: true });
    await page.$eval('[data-template-tag="#원서접수:ticket-field"]', button => button.closest('details').open = true);
    await page.click('[data-template-tag="#원서접수:ticket-field"]');
    const linkedHtml = await page.evaluate(() => window.ApplyHubExamListEditor.instance.getHtml());
    assert(linkedHtml.includes('data-template-tag-value="@{원서접수:ticket-field}"'), 'Inserting a question keeps its stable data binding');
    await page.evaluate(() => window.ApplyHubExamListEditor.instance.insertHtml('<p>페이지 저장 확인</p>'));
    await page.click('#templateEditorPage [data-save-template-editor]');
    await page.waitForFunction(() => document.querySelector('#templateEditorStatus')?.textContent.includes('저장했습니다'));
    const stored = (await service.getTemplates()).find(row => row.id === template.id);
    assert(!stored.contentHtml.includes('data-template-tag-example'), 'Preview applicant values are not embedded in the saved template');
    assert.equal(new URL(page.url()).pathname, `/templates/${template.id}/edit`, 'Saving keeps the editor page open');
    await page.reload({ waitUntil: 'networkidle0' });
    await page.waitForFunction(() => window.ApplyHubExamListEditor?.instance);
    assert((await page.$eval('#templateEditorSurface', el => el.textContent)).includes('페이지 저장 확인'));
    await page.click('[data-applyhub-editor-preview]');
    await page.waitForSelector('#templatePreviewModal:not(.hidden)');
    assert((await page.$eval('#templatePreviewStage', el => el.textContent)).includes('이 전형의 실제 답변'));
    assert.deepEqual(errors, []);
    console.log('PASS: linked admissions, isolated signup/application tags, page routes, save/reload, preview, active templates and PDF');
  } catch (error) { await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }); console.error(errors); throw error; }
  finally { await browser.close(); }
}
module.exports = { verifyTemplateAdmissions };
