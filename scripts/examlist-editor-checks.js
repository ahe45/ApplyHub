const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const puppeteer = require('puppeteer-core');
const { PDFDocument } = require('pdf-lib');

async function verifyExamListEditor({ services, query, base, call }) {
  const schoolLogo = '/client/assets/logo.png';
  await services.systemService.updateSuperAdminSettings({ ...(await services.systemService.getSuperAdminSettings()), logoImageUrl: schoolLogo });
  await query("INSERT INTO app_unit (track_name,admission_code,admission_name,series_code,series_name,unit_code,unit_name) VALUES ('연결모집','1','연결전형','2','계열','3','모집단위')");
  const schedule = (await services.applicantService.getApplicantSchedules())[0];
  const seededTemplate = (await services.templateService.getTemplates())[0];
  await services.applicantService.saveApplicantSchedule({ ...schedule, admitCardTemplateId: seededTemplate.id });
  const member = await query("INSERT INTO applicant_members (login_id,password_hash,name,email,profile_json,consent_json) VALUES ('editor@example.test','unused','홍길동','editor@example.test',?, '{}')", [JSON.stringify({ birth: '2000-03-01' })]);
  const meta = await query("INSERT INTO app_meta (member_id,examinee_no) VALUES (?,'123100001')", [member.insertId]);
  const nameField = (await services.applicantService.getApplicantFormFields()).find(field => field.systemFieldKey === 'name');
  for (const [key, value] of [[nameField.fieldKey, '홍길동'], ['__applicant_selection_track', '연결모집'], ['__applicant_selection_admission', '연결전형']]) {
    await query("INSERT INTO app_subm (id,applicant_name,email,status,field_key,answer_data) VALUES (?,'홍길동','editor@example.test','submitted',?,?)", [meta.insertId, key, value]);
  }
  const login = await call('/api/auth/login', { id: 'admin', password: '1111' });
  const setup = await call('/api/auth/password/setup', { password: 'EditorTest1234', passwordConfirm: 'EditorTest1234' }, login.cookie);
  const cookie = setup.cookie || login.cookie;
  const browser = await puppeteer.launch({ executablePath: process.env.EDGE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('dialog', dialog => dialog.accept());
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  const output = path.resolve(__dirname, '../.tmp-examlist-editor');
  fs.mkdirSync(output, { recursive: true });
  try {
    await page.setViewport({ width: 1800, height: 1100 });
    const separator = cookie.indexOf('=');
    await browser.setCookie({ name: cookie.slice(0, separator), value: cookie.slice(separator + 1), url: base });
    await page.goto(base + '/templates', { waitUntil: 'networkidle0' });
    await page.waitForSelector('[data-template-edit]');
    assert.equal(await page.$eval('[data-template-edit]', button => button.disabled), false);
    await page.waitForSelector('[data-template-edit]:not([disabled])');
    await page.$eval('[data-template-edit]', button => button.click());
    await page.waitForFunction(() => window.ApplyHubExamListEditor?.instance || document.getElementById('templateEditorStatus')?.textContent.includes('못했습니다'), { timeout: 15000 });
    const status = await page.$eval('#templateEditorStatus', el => el.textContent);
    assert(await page.evaluate(() => !!window.ApplyHubExamListEditor.instance), status + '\n' + errors.join('\n'));
    await page.waitForSelector('.examlist-object-size-control');
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert.equal(await page.$eval('[data-applyhub-zoom=reset]', n => n.textContent), '100%', 'The editor opens at 100% without automatically fitting');
    assert.equal(await page.$eval('[data-template-editor-canvas]', n => n.dataset.templateEditorCanvasZoomMode), 'manual');
    assert(await page.$eval('#templateEditorSurface', n => Math.abs(n.getBoundingClientRect().width / n.offsetWidth - 1) < 0.001), 'Initial paper scale is physically 100%');
    await require('./editor-layout-checks').verifyEditorLayout(page, browser);
    await require('./template-document-layout-checks').verifyTemplateDocumentLayout({ page, services });
    await page.click('[data-applyhub-editor-preview]');
    await page.waitForSelector('#templatePreviewModal:not(.hidden)');
    await page.waitForFunction(() => {
      const photo = document.querySelector('#templatePreviewStage .examinee-photo-token-image');
      return photo?.getAttribute('src') === '/client/assets/template-preview-photo.png' && photo.complete && photo.naturalWidth > 0;
    });
    assert.equal(await page.$('#templatePreviewStage .examinee-photo-placeholder'), null);
    await page.click('#templatePreviewModal .modal-header [data-close-modal]');
    const actualPrintWithoutPhoto = await services.templateService.renderTemplateWithExaminee('<p>@{수험생사진}</p>', { name: '실제 수험생' });
    assert(actualPrintWithoutPhoto.includes('사진 미등록') && !actualPrintWithoutPhoto.includes('template-preview-photo.png'), 'Sample photos are limited to template previews');
    const actualPhoto = Buffer.from('actual-photo-fixture');
    const actualPrintWithPhoto = await services.templateService.renderTemplateWithExaminee('<p>@{수험생사진}</p>', { name: '실제 수험생', photoBlob: actualPhoto, photoMime: 'image/png' });
    assert(actualPrintWithPhoto.includes(actualPhoto.toString('base64')) && !actualPrintWithPhoto.includes('template-preview-photo.png'), 'Printing continues to use the actual applicant photo');
    assert.match(await page.$eval('.template-editor-page-header h2', n => n.textContent), /^수험표 양식 - /);
    assert.equal(await page.$('.template-editor-page-header a'), null);
    assert.equal(await page.$('[data-editor-recruitment], [data-editor-data-source]'), null);
    assert.equal(await page.$eval('[data-template-editor-canvas]', n => n.getBoundingClientRect().width), 818, 'Canvas panel uses the original fixed width');
    assert.equal(await page.$eval('#templateEditorStatus', n => n.getClientRects().length), 0);
    const beforeZoom = await page.evaluate(() => window.ApplyHubExamListEditor.instance.getHtml());
    for (const [action, expected] of [['reset', 1], ['in', 1.1], ['out', 1]]) {
      await page.click(`[data-applyhub-zoom="${action}"]`);
      await page.waitForFunction(value => {
        const surface = document.querySelector('#templateEditorSurface');
        return Math.abs(surface.getBoundingClientRect().width / surface.offsetWidth - value) < 0.01;
      }, {}, expected);
      assert.equal(await page.$eval('[data-applyhub-zoom=reset]', n => n.textContent), Math.round(expected * 100) + '%');
    }
    await page.$eval('[data-template-editor-canvas]', n => n.dispatchEvent(new WheelEvent('wheel', { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -100, clientX: n.getBoundingClientRect().left + 50, clientY: n.getBoundingClientRect().top + 50 })));
    await page.waitForFunction(() => document.querySelector('[data-template-editor-canvas]').dataset.templateEditorCanvasZoom === '1.1');
    await page.click('[data-applyhub-zoom=fit]');
    await page.waitForFunction(() => {
      const canvas = document.querySelector('[data-template-editor-canvas]'), paper = document.querySelector('#templateEditorSurface').getBoundingClientRect();
      return canvas.dataset.templateEditorCanvasZoomMode === 'fit' && paper.width <= canvas.clientWidth && paper.height <= canvas.clientHeight;
    });
    assert.equal(await page.evaluate(() => window.ApplyHubExamListEditor.instance.getHtml()), beforeZoom, 'Zoom must not change the printable document');
    assert(await page.$eval('#templateEditorRuntimeHost', n => Math.abs(n.getBoundingClientRect().bottom - innerHeight) <= 2), 'The editor fills the screen without a footer gap');
    await page.evaluate(() => window.ApplyHubExamListEditor.instance.setHtml('<div class="template-doc"><p><br></p></div>'));
    await page.click('#templateEditorSurface p');
    await page.click('[data-template-insert=table]');
    await page.click('[data-template-insert=table-confirm]');
    await page.waitForSelector('#templateEditorSurface table td');
    await page.hover('#templateEditorSurface table td');
    const insertedBackgrounds = await page.$eval('#templateEditorSurface table', table => [table, ...table.querySelectorAll('tr, td, th')].filter(n => getComputedStyle(n).backgroundColor !== 'rgba(0, 0, 0, 0)').map(n => [n.tagName, n.className, getComputedStyle(n).backgroundColor, n.getAttribute('style')]));
    assert.deepEqual(insertedBackgrounds, [], 'Inserted tables have no shading, including when hovered');
    await page.evaluate(() => {
      const surface = document.querySelector('#templateEditorSurface');
      surface.querySelector('td').style.backgroundColor = '#ffe599';
      surface.dispatchEvent(new InputEvent('input', { bubbles: true }));
    });
    assert.match(await page.evaluate(() => window.ApplyHubExamListEditor.instance.getHtml()), /background(?:-color)?:\s*(?:rgb\(255, 229, 153\)|#ffe599)/, 'Authored cell shading remains supported');
    await page.evaluate(html => window.ApplyHubExamListEditor.instance.setHtml(html), beforeZoom);
    await page.evaluate(() => window.ApplyHubExamListEditor.instance.setHtml('<div class="template-doc"><p><br></p></div>'));
    await page.click('#templateEditorSurface p');
    await page.click('[data-template-image-insert-toggle]');
    await page.click('[data-template-insert-school-logo]');
    await page.waitForFunction(src => {
      const logo = document.querySelector('#templateEditorSurface img[alt="학교 로고"]');
      return logo?.getAttribute('src') === src && logo.complete && logo.naturalWidth > 0;
    }, {}, schoolLogo);
    const logoHtml = await page.evaluate(() => window.ApplyHubExamListEditor.instance.getHtml());
    assert(logoHtml.includes(schoolLogo), 'Configured branding is inserted for an ordinary administrator');
    await page.click('[data-save-template-editor]');
    await page.waitForFunction(() => document.querySelector('#templateEditorStatus').textContent.includes('저장했습니다'));
    const logoTemplateId = await page.evaluate(() => state.templateEditor.activeTemplateId);
    assert((await services.templateService.getTemplates()).find(template => template.id === logoTemplateId).contentHtml.includes(schoolLogo));
    await page.reload({ waitUntil: 'networkidle0' });
    await page.waitForFunction(src => document.querySelector('#templateEditorSurface img[alt="학교 로고"]')?.getAttribute('src') === src, {}, schoolLogo);
    await services.templateService.updateTemplate(logoTemplateId, seededTemplate);
    await page.evaluate(html => window.ApplyHubExamListEditor.instance.setHtml(html), beforeZoom);
    await page.screenshot({ path: path.join(output, 'editor.png'), fullPage: true });
    await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
    await page.screenshot({ path: path.join(output, 'editor-dark.png'), fullPage: true });
    await page.evaluate(() => document.documentElement.dataset.theme = 'light');
    await page.setViewport({ width: 1366, height: 900 });
    await page.click('[data-applyhub-zoom="fit"]');
    const zoom = await page.$eval('[data-template-editor-canvas]', el => Number(el.dataset.templateEditorCanvasZoom));
    assert(zoom > 0 && zoom < 1, 'Fit zoom makes the paper visible on a smaller screen');
    assert(await page.$eval('[data-template-editor-canvas]', n => { const paper = n.querySelector('#templateEditorSurface').getBoundingClientRect(); return paper.width <= n.clientWidth && paper.height <= n.clientHeight; }), 'Fit includes the entire page in both dimensions');
    await page.screenshot({ path: path.join(output, 'editor-1366.png'), fullPage: true });
    await page.setViewport({ width: 1800, height: 1100 });
    await page.waitForFunction(previous => Number(document.querySelector('[data-template-editor-canvas]').dataset.templateEditorCanvasZoom) > previous, {}, zoom);
    await page.click('[data-applyhub-zoom="reset"]');
    assert.deepEqual(errors, []);
    const panel = await page.$eval('#templatePagePropertiesPanel', el => el.textContent);
    for (const label of ['표지/본문', '수험생 데이터', '생성단위', '타고사실', '페이지번호', '인식기준']) assert(!panel.includes(label), label);
    const templateId = await page.evaluate(() => state.templateEditor.activeTemplateId);
    const original = (await services.templateService.getTemplates()).find(template => template.id === templateId);
    await page.evaluate(() => window.ApplyHubExamListEditor.instance.setHtml('<div class="template-doc"><p><span class="template-token" data-template-tag-value="@{생년월일}" style="font-size:22pt;color:#ff0000">생년월일</span></p></div>'));
    await page.click('#templateEditorSurface [data-template-tag-value]', { clickCount: 2 });
    await page.waitForSelector('.data-tag-format-modal-overlay', { visible: true });
    await page.select('[data-data-tag-format-field="preset"]', 'YYYY년 MM월 DD일');
    await page.screenshot({ path: path.join(output, 'date-format.png'), fullPage: true });
    await page.click('[data-action="save-data-tag-format-modal"]');
    await page.waitForFunction(() => document.querySelector('#templateEditorSurface [data-template-tag-value]').textContent === '2000년 03월 01일');
    await page.click('#templateEditorToolbarHost [data-template-insert="qrcode"]');
    await page.waitForSelector('.examlist-generated-object-source-modal', { visible: true });
    await page.$eval('.examlist-generated-object-source-modal [data-examlist-generated-object-source-close]', button => button.focus());
    await page.keyboard.press('Escape');
    assert(await page.$('#templateEditorPage'), 'Cancelling a code picker keeps the editor open');
    await page.click('#templateEditorToolbarHost [data-template-insert="qrcode"]');
    await page.waitForSelector('.examlist-generated-object-source-modal', { visible: true });
    await page.$eval('.examlist-generated-object-source-modal [data-examlist-generated-object-source-option="candidate.name"]', button => button.closest('details').open = true);
    await page.screenshot({ path: path.join(output, 'code-source.png'), fullPage: true });
    await page.click('.examlist-generated-object-source-modal [data-examlist-generated-object-source-option="candidate.name"]');
    await page.waitForFunction(() => document.querySelector('#templateEditorSurface img[data-template-object-type="qrcode"]')?.src.includes(encodeURIComponent('홍길동')));
    const savedHtml = await page.evaluate(() => window.ApplyHubExamListEditor.instance.getHtml());
    assert(savedHtml.includes('data-template-tag-format="YYYY년 MM월 DD일"'));
    assert(savedHtml.includes('data-template-object-source="candidate.name"'));
    assert(!savedHtml.includes('2000년 03월 01일'), 'Sample tag text is never saved as applicant data');
    await page.click('[data-applyhub-editor-preview]');
    await page.waitForSelector('#templatePreviewModal:not(.hidden)');
    assert((await page.$eval('#templatePreviewStage', el => el.textContent)).includes('2000년 03월 01일'));
    assert.equal(await page.$eval('#templatePreviewStage [style*="22pt"]', el => getComputedStyle(el).fontSize), '29.3333px');
    await page.click('#templatePreviewModal .modal-header [data-close-modal]');
    await page.click('#templateEditorPage [data-save-template-editor]');
    await page.waitForFunction(() => document.querySelector('#templateEditorStatus').textContent.includes('저장했습니다'));
    const saved = (await services.templateService.getTemplates()).find(template => template.id === templateId);
    assert(saved.contentHtml.includes('data-template-tag-format'));
    const rendered = await services.templateService.renderTemplateWithExaminee(saved.contentHtml, { name: '실제지원자', birth: '2001-02-03', examineeNo: '12345' });
    assert(rendered.includes('2001년 02월 03일'));
    assert(rendered.includes('font-size: 22pt') || rendered.includes('font-size:22pt'));
    assert(rendered.includes('실제지원자 QR코드'));
    await services.applicantService.saveApplicantSchedule({ ...schedule, admitCardTemplateId: templateId });
    const pdf = await services.admitCardService.buildAdmitCardPdfBufferFromRecord({ track: '연결모집', admission: '연결전형', name: '실제지원자', birth: '2001-02-03', examineeNo: '12345' });
    assert.equal((await PDFDocument.load(pdf)).getPageCount(), 1);
    await services.templateService.updateTemplate(templateId, original);
    await page.goto(base + '/templates', { waitUntil: 'networkidle0' });
    await page.setViewport({ width: 1440, height: 1000 });
    await require('./template-editor-smoke-test').verifyTemplateEditor(page);
    assert.deepEqual(errors, []);
    console.log('PASS: ExamList editor, excluded panels, responsive zoom, date formats, QR sources, saved formatting, PDF and table editing');
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
    console.error('Browser errors:', errors);
    throw error;
  } finally { await browser.close(); }
}
module.exports = { verifyExamListEditor };
