const assert = require('node:assert/strict');
const factories = require('../client/app/state-factories');
const { createSystemSettingsController } = require('../client/features/system/settings');

const saveButton = { disabled: true };
global.document = { querySelector: () => saveButton, getElementById: () => null };
global.normalizeAdmitCardDataSource = value => value === 'submission' ? 'submission' : 'examinee';
const initial = { schoolName: '기존대학교', schoolLogoImageUrl: '/old-school-logo.png' };
const state = { systemSettings: factories.createSystemSettingsState(initial), systemDataDeletion: factories.createSystemDataDeletionState() };
const controller = createSystemSettingsController({ state, normalizeSystemSettingsPayload: factories.normalizeSystemSettingsPayload, syncAccountCreateDescription() {}, syncAutoLogoutTimer() {} });
assert.equal(controller.syncSystemSettingsDirtyState(), false);
assert.equal(saveButton.disabled, true);
state.systemSettings.schoolName = '변경대학교';
assert.equal(controller.syncSystemSettingsDirtyState(), true, 'School name alone must enable saving');
assert.equal(saveButton.disabled, false);
assert(controller.getSystemSettingsChangeSummaries().some(item => item.label === '학교명'));
state.systemSettings.schoolName = initial.schoolName;
assert.equal(controller.syncSystemSettingsDirtyState(), false, 'Reverting name clears dirty state');
state.systemSettings.schoolLogoImageUrl = '/new-school-logo.png';
assert.equal(controller.syncSystemSettingsDirtyState(), true, 'Logo alone must enable saving');
assert.equal(saveButton.disabled, false);
assert(controller.getSystemSettingsChangeSummaries().some(item => item.label === '학교 로고'), 'Replacing one custom logo with another is a change');
state.systemSettings.isUploadingLogo = true;
controller.syncSystemSettingsDirtyState();
assert.equal(saveButton.disabled, true);
state.systemSettings.isUploadingLogo = false;
controller.syncSystemSettingsDirtyState();
assert.equal(saveButton.disabled, false);
controller.applySystemSettingsPayload({ ...state.systemSettings });
assert.equal(saveButton.disabled, true, 'Saved branding clears dirty state');
state.systemSettings.schoolLogoImageUrl = '';
assert.equal(controller.syncSystemSettingsDirtyState(), true, 'Resetting the logo must enable saving');
state.systemSettings.schoolLogoImageUrl = '/new-school-logo.png';
assert.equal(controller.syncSystemSettingsDirtyState(), false, 'Reverting logo clears dirty state');
console.log('PASS: independent school name/logo changes, custom logo replacement, reset, upload guard and saved/reverted states');
